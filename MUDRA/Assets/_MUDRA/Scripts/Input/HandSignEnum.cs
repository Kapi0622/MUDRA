public enum HandSign
{
    // --- 片手：詠唱印 ---
    Open = 0,       // 壱印「開」パー（全指開き）
    Fist = 1,       // 弐印「握」グー（全指閉じ）
    Point = 2,      // 参印「指」人差し指のみ伸ばす
    Scissors = 5,   // 肆印「刃」チョキ（人差し指+中指）
    Palm = 6,       // 伍印「掌」親指だけ折る

    // --- 片手：特殊印 ---
    Release = 3,    // 発動印「射」親指曲げ+人差し指+小指
    Cancel = 4,     // 解除印「散」小指のみ伸ばす
    Guard = 7,      // 捌印「盾」親指のみ伸ばし（ガード専用）

    // --- 両手印 ---
    Union = 8,      // 陸印「合」両手合わせ
    DoubleScissors = 9, // 㯃印「刃」二つ
}